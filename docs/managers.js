/* ==========================================================================
   managers.js — THE manager profile page (managers.html).

   THE ONLY ONE. profile.html was a second, single-manager view of the same
   files; it was retired and this page absorbed it. A reader who wants one
   person deep-links to them (#<manager_id>) and lands on their profile in the
   stack.

   GROUP-GENERIC BY CONSTRUCTION. There is no roster, no manager id and no
   group path anywhere in this file, and there is no `if (manager === ...)`
   anywhere either — the layout a profile takes is a data value, not a branch.
   It renders whatever standings.json returns for ?group=, in rank order, and
   treats EVERY persona field as optional. That is not defensive politeness:
   2 of the 24 managers across the four leagues have no persona content at all
   and 12 more have only the four original prose fields, and each of them still
   has to look like a finished page rather than a broken one.

   Reads, in one Promise.all:
     data/<group>/personas.json    prose + creative — GENERATED by sync_personas.py
     data/<group>/standings.json   exact — the picks, and nothing else
     data/team_marks.json          team identity — GENERATED by build_team_marks.py
     assets/art_slots.json         which picture, via resolveArt()
     assets/portraits/index.json   team colour fallback when no persona colour

   NO projection.json. Every number on this page is exact arithmetic off
   standings.json; the model lives on the home page's Board 2 and on
   analytics.html, which are built to frame it.

   Only standings.json is required. Every other file is allowed to 404: that is
   the normal state for a league with no art and no prose, and the page must
   degrade to "picks and a name" without a placeholder anywhere.

   ---------------------------------------------------------------------------
   THE COMPOSITION MODEL, which is the one idea in this file.

   Every profile is the same eight BLOCKS — portrait, headline, dossier, picks,
   scouting, modules, quote, band. Each block is a function that returns markup
   or returns the empty string when it has nothing to say. A LAYOUT VARIANT is
   then nothing but an arrangement of those eight strings into two column
   wrappers; profile.css does the rest.

   The consequence worth stating: because an absent block is an empty string
   rather than a placeholder, a variant composes identically whether it was
   handed eight blocks or two. That is what makes the tone gate safe. A
   straight-register profile is not a roast page with holes in it — the holes
   never enter the markup, and the surviving blocks close up around them.

   THE TONE GATE is the one rule in here that is not cosmetic. See TONE_BLOCKS
   in site.js. Two independent gates, because the strict register is somebody's
   parents: sync_personas.py nulls what a register withholds before it leaves
   the repo, and this file refuses to render it even if it arrives.
   ========================================================================== */
'use strict';

// fmtSigned / fmtLine / pct, the TONE_BLOCKS gate, toneOf() and has() live in
// site.js. They stay there because the tone gate is the one rule on this site
// where a second copy would be a second, silently-drifting answer to "may this
// person be captioned with a fatal flaw". These are classic scripts sharing
// one global lexical scope, so they are in scope here by name.

