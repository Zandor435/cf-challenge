// ---------------------------------------------------------------------------
// WHICH SIDE THE PORTRAIT SITS ON.
//
// Every manager in every league renders SIDELINE now, so the rhythm down the
// page can no longer come from switching variants. It comes from switching
// SIDES: position 1 puts the portrait left, position 2 right, position 3 left,
// and so on. `pf--align-right` is the only thing that says so; profile.css
// flips the grid and the bleed margin off that one class and the DOM order of
// the two columns never changes, which is what keeps the reading order — and
// therefore the tab order and the screen-reader order — identical on both
// sides.
//
// PINNED TO profile_order, WHICH IS NOT THIS PAGE'S ORDER. The page renders in
// STANDINGS order; profile_order is the manager's index in
// groups/<group>/personas.json, published by sync_personas.py. Those two lists
// disagree, and pinning to the persona list is the deliberate choice: a
// manager's side must not flip mid-season because they won or lost a game.
//
// The consequence, stated plainly because it is visible: except where the two
// orders happen to line up, the sides down the page do NOT read
// left/right/left. Two managers who sit next to each other in the standings
// can both be portrait-left. That is the cost of a stable side, and it is the
// side that was specified as the thing to protect.
//
// FALLBACK to the rank index when profile_order is absent — an older published
// personas.json, or a manager with no persona record at all. Alternating off
// something is better than every profile silently collapsing to the left.
function alignRight(persona, index) {
  const order = (persona && Number.isInteger(persona.profile_order))
    ? persona.profile_order : index;
  return order % 2 === 1;
}

// The icon per module BLOCK — never per person. This file cannot know that a
// particular manager's gag is about Texas, and a per-person mark would be the
// first `if (manager === ...)` in a file that has none.
const MODULE_META = {
  draft_tendency: { icon: '⇄', label: 'Draft tendency' },
  fatal_flaw:     { icon: '!',      label: 'Fatal flaw' },
  running_gag:    { icon: '↻', label: 'Running gag' },
  rival:          { icon: '⚔', label: 'Rival' },
};

// Read one sub-key off persona.modules[key] without caring whether the block,
// or `modules` itself, exists. Every profile field is optional; this keeps the
// call sites from restating that four times per module.
function mod(p, key, sub) {
  const blocks = p && p.modules;
  const block = blocks && blocks[key];
  return block && has(block[sub]) ? block[sub] : null;
}

function themeVars(p, fallbackColor) {
  // The accent is an EDITORIAL choice first (persona theme), the team colour
  // second, and the stylesheet's own default last. A manager with no creative
  // direction still gets a coloured page rather than a grey one.
  const t = (p && p.theme) || {};
  const pairs = [
    ['--profile-accent', has(t.accent) ? t.accent : fallbackColor],
    ['--profile-accent-secondary', t.accent_secondary],
    ['--profile-paper', t.paper],
    ['--profile-ink', t.ink],
  ];
  const out = pairs
    .filter((kv) => has(kv[1]))
    .map((kv) => `${kv[0]}:${esc(String(kv[1]))}`)
    .join(';');
  return out ? ` style="${out}"` : '';
}

// ---------- block 1 — portrait ---------------------------------------------
// resolveArt() returns null for a group that declares no profile art. Null
// means the block is not emitted AT ALL and the layout closes up: no grey box,
// no placeholder, no alt stub, no empty gutter. A manager without a picture
// should look like a manager whose page was designed without one.
//
// TWO SLOTS, TRIED IN ORDER, and an explicit persona asset beats both.
// profile_page_hero is the torn, alpha-keyed cut; profile_hero is the opaque
// rectangle and the fallback for every group that never declared the page
// slot. Both names survive the retirement of profile.html — they name CUTS OF
// ART, not pages.
//
// WHY .is-cut IS GATED ON THE TWO SLOTS DISAGREEING rather than on the page
// slot merely answering: family declares profile_page_hero pointing at the
// SAME file as profile_hero, because its art is real photographs deliberately
// never given a torn edge. Keying the frameless treatment on "the page slot
// answered" would apply a cut treatment to every family portrait for a cut
// that does not exist. The treatment belongs to a DISTINCT cut, so that is
// what is tested — and .is-cut is what stops profile.css adding a SECOND,
// synthetic tear to art that is already ragged in the pixels.
//
// The alt text is the manager's name: this is a portrait of a person and it is
// primary content, not decoration, so it is never alt="".
function blockPortrait(ctx, m, p, index) {
  const authored = p && p.assets && has(p.assets.hero) ? p.assets.hero : null;
  const cut = resolveArt(ctx.groupId, 'profile_page_hero', ctx.week, { id: m.manager_id });
  const card = resolveArt(ctx.groupId, 'profile_hero', ctx.week, { id: m.manager_id });
  const src = authored || cut || card;
  if (!src) return { html: '', hasArt: false };

  // THE MANIFEST IS THE DECLARATION THAT THE ART EXISTS, and it has to be,
  // now that portraits load lazily. art_slots.json resolves a PATTERN — every
  // browns manager gets `assets/profiles/browns/<id>-ripped.webp` whether or
  // not that file was ever made — so josh and marc resolve to paths that 404.
  // Eagerly that was self-correcting: the error fired at once and the runtime
  // handler re-tagged them to DOSSIER before anyone saw it. Lazily the error
  // does not fire until the section scrolls into view, so they would render as
  // a two-column SIDELINE with an empty column and then visibly reflow.
  //
  // heroes.json is generated by scanning the profile art directory, so
  // "absent from the manifest" is the same statement as "not on disk" — made
  // BEFORE the request rather than after it. Side benefit: the page stops
  // emitting 404s for art that was never generated.
  //
  // GUARDED on the manifest being non-empty. A 404 on heroes.json itself
  // leaves the map empty, and treating that as "no manager has art" would
  // blank every portrait on the site; an empty map therefore means "cannot
  // say", and every path is allowed through to the old error-handler tier.
  const manifestKnown = Object.keys(ctx.heroSizes).length > 0;
  if (manifestKnown && !ctx.heroSizes[src]) {
    // Loud, because the other way this happens is a real asset that was added
    // without re-running build_profile_heroes.py — which would now silently
    // hide it rather than merely reflow the page.
    console.warn(`[profiles] ${m.manager_id}: ${src} is not in assets/profiles/heroes.json — ` +
      `treating as no art. If this file exists, re-run scripts/build_profile_heroes.py.`);
    return { html: '', hasArt: false };
  }

  const isCut = !!(!authored && cut && cut !== card);

  // RESERVE THE SPACE BEFORE THE IMAGE ARRIVES. assets/profiles/heroes.json is
  // a generated path -> [w, h] map that exists for exactly this: without it
  // every portrait is a zero-height box until it loads, and eight profiles
  // arriving at eight different moments reflow the page under the reader —
  // which also makes any deep link or scripted scroll land somewhere else by
  // the time it settles. Setting the art's OWN ratio (not a placeholder one)
  // means the box never has to change size at all.
  //
  // A missing entry is survivable: no ratio is declared, the figure sizes to
  // the image on load exactly as it would have, and only the shift comes back.
  const dim = ctx.heroSizes[src];
  const ratio = (Array.isArray(dim) && dim[0] > 0 && dim[1] > 0)
    ? ` style="--pf-art-ratio:${Number(dim[0])}/${Number(dim[1])}"` : '';

  // LAZY BELOW THE FOLD, EAGER FOR THE FIRST SECTION. This page is one
  // continuous scroll of up to eight full-bleed sections, so shipping every
  // hero eagerly means the reader downloads seven portraits they may never
  // reach.
  //
  // This was deliberately NOT lazy in the first cut of this file, and the
  // objection then was real: a lazy portrait with no reserved box rendered its
  // column as empty space, which reads as the no-art state when it is nothing
  // of the kind. Reserving the art's true aspect ratio (above) removed that —
  // the box is the right size before the bytes arrive, so laziness now costs
  // nothing. The two changes only work together; do not lazy-load these again
  // if the ratio reservation is ever dropped.
  //
  // The first section is eager because it IS the fold — deferring it would
  // delay the page's primary content behind an intersection callback.
  const lazy = index > 0 ? ' loading="lazy"' : '';
  return {
    hasArt: true,
    html: `<figure class="pf-portrait${isCut ? ' is-cut' : ''}"${ratio}>
      <img src="${esc(src)}" alt="${esc(m.display_name)}" decoding="async"${lazy}>
    </figure>`,
  };
}

// ---------- block 2 — headline ---------------------------------------------
// archetype eyebrow / name / thesis. An authored nameplate image replaces the
// typographic name, but the <h2> STAYS IN THE DOM carrying the real text and
// is only visually hidden — the heading outline and the accessible name must
// not depend on whether an art asset happened to be generated.
function blockHeadline(m, p) {
  const archetype = p && has(p.archetype) ? p.archetype
    : (p && has(p.epithet) ? p.epithet : null);
  // thesis is the new one-liner; tagline is what the four original personas
  // already carry. Same slot, so an un-migrated persona still reads right.
  const thesis = p && has(p.thesis) ? p.thesis
    : (p && has(p.tagline) ? p.tagline : null);
  const plate = p && p.assets && has(p.assets.nameplate) ? p.assets.nameplate : null;

  return `<header class="pf-headline">
    ${archetype ? `<p class="pf-archetype">${esc(archetype)}</p>` : ''}
    <h2 class="pf-name${plate ? ' sr-only' : ''}" id="${esc(m.manager_id)}-name">${esc(m.display_name)}</h2>
    ${plate ? `<img class="pf-nameplate" src="${esc(plate)}" alt="" decoding="async">` : ''}
    ${thesis ? `<p class="pf-thesis">${esc(thesis)}</p>` : ''}
    <div class="pf-headline-rule" aria-hidden="true"></div>
  </header>`;
}

// ---------- block 3 — dossier ----------------------------------------------
// The dark card. Every row optional; the block itself disappears when the
// persona declares no dossier at all rather than rendering an empty slab.
function blockDossier(m, p) {
  const d = (p && p.dossier) || {};
  const nicknames = Array.isArray(d.nicknames) ? d.nicknames.filter(has) : [];
  const rows = [];
  if (has(d.role)) {
    // "Role", not "Panel role". The reference mockup reads PANEL ROLE because
    // it was drawn for The Panel; baking that in would print the name of one
    // league on the profiles of the other three, in the one file whose whole
    // contract is that it knows nothing about any group.
    rows.push(['Role', `<span class="is-name">${esc(d.role)}</span>`]);
  }
  if (nicknames.length) {
    rows.push(['Nicknames', esc(nicknames.join(', '))]);
  }
  if (has(d.known_for)) rows.push(['Known for', esc(d.known_for)]);

  // hometown / college / drafted / status render as a ruled facts strip rather
  // than four more of the rows above — they are reference data, not prose.
  const facts = [
    ['College', d.college],
    ['Hometown', d.hometown],
    ['Drafted', d.drafted],
    ['Status', d.status],
  ].filter((f) => has(f[1]));

  if (!rows.length && !facts.length) return '';

  const rowHtml = rows.map((r) => `<div class="pf-dossier-row">
      <dt>${esc(r[0])}</dt><dd>${r[1]}</dd>
    </div>`).join('');
  const factHtml = facts.length
    ? `<div class="pf-facts">${facts.map((f) => `<div class="pf-fact">
        <dt>${esc(f[0])}</dt><dd>${esc(f[1])}</dd>
      </div>`).join('')}</div>`
    : '';
  return `<dl class="pf-dossier">${rowHtml}${factHtml}</dl>`;
}

// ---------- block 4 — picks ------------------------------------------------
// ALWAYS renders. This is the page's guarantee that a manager with zero flavor
// content still gets a real page: live scoring is something everybody has.
//
// THE COLUMN SET IS DATA-DRIVEN, and that is the whole reason this is written
// the way it is. Preseason there is no delta worth printing — every pick's
// banked_delta is just its line back — so the Δ column is omitted and the four
// remaining columns take the width. The moment as_of_week is an integer the
// column appears, with no second table implementation and no redesign. That is
// the "current/result columns slot in during the season" requirement, met by
// letting one renderer read the week rather than by building two tables.
//
// Every value here is exact arithmetic off standings.json, which copied line
// and conference from data/team_win_totals_2026.json at draft entry. Nothing
// on this page hardcodes a pick, a line or a conference.
function blockPicks(m, ctx) {
  const picks = m.picks || [];
  const live = Number.isInteger(ctx.week);
  const cols = live
    ? 'minmax(0, 1fr) 88px 84px 104px 86px'
    : 'minmax(0, 1fr) 100px 92px 116px';
  const label = live ? `Week ${ctx.week} board` : `${ctx.season} preseason picks`;

  if (!picks.length) {
    // Pre-draft is a real state, not a failure — say so instead of printing an
    // empty table.
    return `<section class="pf-picks" aria-label="Picks">
      <div class="pf-picks-head"><span class="pf-label">${esc(label)}</span></div>
      <div class="pf-table" style="--pf-pick-cols:${cols}">
        <p class="pf-picks-empty">No picks yet — this league hasn&rsquo;t drafted.</p>
      </div>
    </section>`;
  }

  const head = `<div class="pf-row is-head" aria-hidden="true">
    <span>Team</span><span>Conf</span><span>Line</span><span>Call</span>${live ? '<span>&Delta;</span>' : ''}
  </div>`;

  const rows = picks.map((pk) => {
    const over = pk.direction === 'O';
    const mark = ctx.marks[pk.team] || null;
    const chip = mark && mark.logo
      ? `<span class="pf-mark"><img src="${esc(mark.logo)}" alt="" decoding="async"></span>`
      // The chip's type colour is DATA, not a style guess: build_team_marks.py
      // resolves black-or-white against the team's own primary so a light
      // primary (Wake Forest gold) does not draw white type on gold.
      : `<span class="pf-mark"${mark && mark.color ? ` style="--pf-team-color:${esc(mark.color)};--pf-team-ink:${esc(mark.ink || '#fff')}"` : ''} aria-hidden="true">${esc(mark ? mark.abbr : (pk.team || '?').slice(0, 3).toUpperCase())}</span>`;
    const d = Number(pk.banked_delta);
    const dCls = d > 0 ? ' pos' : d < 0 ? ' neg' : '';
    // The call is stated as a WORD and given a distinct shape (filled vs
    // outlined) as well as a colour. The Over/Under distinction is never
    // carried by colour alone.
    return `<div class="pf-row${pk.status === 'DEAD' ? ' is-dead' : ''}">
      <div class="pf-team">${chip}<span class="pf-team-name">${esc(pk.team)}</span></div>
      <span class="pf-conf" data-label="Conf">${esc(pk.conference || '—')}</span>
      <span class="pf-line" data-label="Line">${fmtLine(pk.line)}</span>
      <span class="pf-call ${over ? 'over' : 'under'}">${over ? 'Over' : 'Under'}</span>
      ${live ? `<span class="pf-delta${dCls}" data-label="Delta">${fmtSigned(d)}</span>` : ''}
    </div>`;
  }).join('');

  return `<section class="pf-picks" aria-label="Picks">
    <div class="pf-picks-head"><span class="pf-label">${esc(label)}</span></div>
    <div class="pf-table" style="--pf-pick-cols:${cols}">${head}${rows}</div>
  </section>`;
}

// ---------- block 5 — scouting report --------------------------------------
// Paragraphs split on a blank line, exactly as authored in personas.md.
function blockScouting(p) {
  if (!p || !has(p.backstory)) return '';
  const paras = String(p.backstory).split(/\n\s*\n/).map((t) => t.trim()).filter(Boolean);
  if (!paras.length) return '';
  return `<section class="pf-scouting" aria-label="Scouting report">
    <span class="pf-label">Scouting report</span>
    <div class="pf-scouting-body">${paras.map((t) => `<p>${esc(t)}</p>`).join('')}</div>
  </section>`;
}

// ---------- block 6 — personality modules ----------------------------------
// TONE-GATED, and this is the gate that matters. `allow` comes from toneOf();
// a withheld block never enters the markup — it is not hidden with CSS, it is
// not rendered.
//
// COMPOSITION IS NOT THREE IDENTICAL CARDS. The first module takes .is-lead —
// full width, accent rule, tinted ground — and the rest sit in the auto-fit
// band beside it. auto-fit is load-bearing rather than cosmetic: the tone gate
// decides how many modules exist, a straight-register manager gets exactly one
// and a roast-register manager with a full persona gets four, and every count
// between happens. A fixed column count sits the one-module manager beside
// that many empty cells.
//
// Rival is a SAME-PAGE anchor, and only when the rival is someone this render
// actually produced — an id that never rendered would be a dead jump.
// sync_personas.py already rejects a rival that is not a manager_id in the
// group; this catches the narrower case where the roster and this render
// disagree.
function blockModules(p, allow, names) {
  if (!p) return '';
  const out = [];

  const push = (key, bodyHtml) => {
    const meta = MODULE_META[key];
    out.push({
      icon: meta.icon,
      label: mod(p, key, 'label') || meta.label,
      // The headline is the module's own; with none authored the block still
      // works — it just leads with its body instead of with a title.
      headline: mod(p, key, 'headline'),
      art: mod(p, key, 'art'),
      body: bodyHtml,
    });
  };

  if (has(p.draft_tendency)) push('draft_tendency', esc(p.draft_tendency));
  if (allow.fatal_flaw && has(p.fatal_flaw)) push('fatal_flaw', esc(p.fatal_flaw));
  if (allow.running_gag && has(p.running_gag)) push('running_gag', esc(p.running_gag));
  if (allow.rival && has(p.rival) &&
      Object.prototype.hasOwnProperty.call(names, String(p.rival))) {
    const rid = String(p.rival);
    push('rival', `<a href="#${encodeURIComponent(rid)}">${esc(names[rid])}</a>`);
  }

  if (!out.length) return '';

  // The grid's track count must equal the number of cells that will actually
  // be filled. profile.css draws the 1px rules by letting the container colour
  // show BETWEEN opaque cells, so an unfilled track paints a grey rectangle
  // rather than nothing. The lead module spans the full width, so the track
  // count is the number of modules after it — floored at 1 so a lone module
  // still has a track to sit in.
  const cols = Math.max(1, out.length - 1);

  return `<section class="pf-modules" aria-label="Profile notes" style="--pf-module-cols:${cols}">${out.map((c, i) => `
    <article class="pf-module${i === 0 ? ' is-lead' : ''}">
      <div class="pf-module-head">
        <span class="pf-module-icon" aria-hidden="true">${c.icon}</span>
        <span class="pf-label">${esc(c.label)}</span>
      </div>
      ${c.headline ? `<h3 class="pf-module-title">${esc(c.headline)}</h3>` : ''}
      <p class="pf-module-body">${c.body}</p>
      ${c.art ? `<img class="pf-spot" src="${esc(c.art)}" alt="" loading="lazy" decoding="async">` : ''}
    </article>`).join('')}</section>`;
}

// ---------- block 7 — pull quote -------------------------------------------
function blockQuote(m, p) {
  const q = p && p.pull_quote;
  if (!q || !has(q.text)) return '';
  const sig = p.assets && has(p.assets.signature) ? p.assets.signature : null;
  const attr = has(q.attribution) ? q.attribution : m.display_name;
  return `<figure class="pf-quote">
    <span class="pf-quote-mark" aria-hidden="true">&ldquo;</span>
    <blockquote class="pf-quote-text">${esc(q.text)}</blockquote>
    <figcaption class="pf-quote-attr">
      <span>${esc(attr)}</span>
      ${sig ? `<img class="pf-signature" src="${esc(sig)}" alt="" decoding="async">` : ''}
    </figcaption>
  </figure>`;
}

// ---------- block 8 — closing band -----------------------------------------
// Both halves or neither: persona_schema.py rejects half a footer at build
// time, so this only has to test that the block exists at all. The seal is
// drawn in CSS when no badge asset was generated — the band is never a black
// bar with a gap in the middle of it.
function blockBand(m, p) {
  const f = p && p.footer;
  if (!f || !has(f.left) || !has(f.right)) return '';
  const badge = p.assets && has(p.assets.badge) ? p.assets.badge : null;
  const seal = badge
    ? `<img class="pf-badge" src="${esc(badge)}" alt="" decoding="async">`
    : `<span class="pf-seal" aria-hidden="true">${esc((m.display_name || '?').slice(0, 1).toUpperCase())}</span>`;
  return `<div class="pf-band">
    <p class="pf-band-half">${esc(f.left)}</p>
    ${seal}
    <p class="pf-band-half is-right">${esc(f.right)}</p>
  </div>`;
}

// ---------- block 9 — jump links -------------------------------------------
function blockJump(m) {
  return `<nav class="pf-jump" aria-label="Profile links">
    <a href="#${esc(encodeURIComponent(m.manager_id))}">Link to ${esc(m.display_name)} &rarr;</a>
    <a href="#top">&uarr; Back to top</a>
  </nav>`;
}

// ---------- one profile ----------------------------------------------------
function profile(m, persona, ctx, index) {
  const p = persona || null;
  const allow = toneOf(p);
  const portrait = blockPortrait(ctx, m, p, index);

  // The variant is a DATA VALUE. persona_schema.py has already rejected any
  // key that is not a known variant, so an unknown one cannot arrive here —
  // but a persona written before `layout` existed carries none at all, which
  // is legal and means the default.
  //
  // ONE OVERRIDE, and it is about honesty rather than taste: SIDELINE,
  // HEADLINER and PROGRAM are all compositions built around a picture. A
  // manager with no art rendered in one of them is a layout with a hole in it,
  // so they fall to DOSSIER, the variant designed to carry a profile on facts
  // alone. This is the no-art tier, not a per-manager special case.
  let layout = (p && has(p.layout) && LAYOUT_TEMPLATES[p.layout]) ? p.layout : DEFAULT_LAYOUT;
  if (!portrait.hasArt && layout !== 'dossier') layout = 'dossier';

  // The alternation is SIDELINE's, and only SIDELINE's. DOSSIER — which is
  // where a manager with no art lands — is a full-width composition with no
  // portrait column to put on either side, so tagging it would be a class that
  // describes nothing. See alignRight() for why the position comes from the
  // persona list rather than from this page's order.
  const alignCls = (layout === 'sideline' && alignRight(p, index))
    ? ' pf--align-right' : '';

  const blocks = {
    portrait: portrait.html,
    headline: blockHeadline(m, p),
    dossier: blockDossier(m, p),
    picks: blockPicks(m, ctx),
    scouting: blockScouting(p),
    modules: blockModules(p, allow, ctx.names),
    quote: blockQuote(m, p),
    band: blockBand(m, p),
    jump: blockJump(m),
  };

  // Team colour is the accent fallback when the persona names no theme. It is
  // used for rules, fills and display type only; --profile-accent-deep is what
  // the small labels read, so a helmet colour never has to clear 4.5:1 raw.
  const fallbackColor = p && has(p.color) ? p.color
    : (ctx.colors[m.manager_id] || null);

  return `<article class="pf pf--${esc(layout)}${alignCls}${portrait.hasArt ? '' : ' has-no-art'}"
    id="${esc(m.manager_id)}"
    aria-labelledby="${esc(m.manager_id)}-name"${themeVars(p, fallbackColor)}>
    ${LAYOUT_TEMPLATES[layout](blocks)}
  </article>`;
}

// ---------- contents -------------------------------------------------------
// The jump strip under the page title. One line, names only, every manager
// linked to their own section — this page can run to eight full-bleed
// chapters, and without it reaching the seventh means scrolling past six.
//
// DRAFT ORDER, i.e. profile_order, i.e. each manager's position in
// groups/<group>/personas.json. The same list the alternating layout is
// pinned to, for the same reason: a contents line that reshuffles itself
// every time somebody wins a game is a contents line nobody can learn.
//
// AND SO IT DOES NOT MATCH THE ORDER OF THE PAGE, which renders in STANDINGS
// order. Stated plainly because it is the one thing about this strip a reader
// could be surprised by: the names read left-to-right in draft order, and the
// sections below them read top-to-bottom in rank order. Deriving the strip
// from `mgrs` as handed in (already rank-sorted) is the one-line change if
// that trade ever reads the wrong way round.
//
// Separators are drawn in CSS, never put in the markup: a screen reader
// should hear four names, not four names and three pipes.
function renderContents(mgrs, personas) {
  const el = $('mgr-contents');
  if (!el || mgrs.length < 2) return;      // one manager is not a contents page

  // Fall back to the rank position when profile_order is absent, exactly as
  // the layout alternation does — the two must not be able to disagree about
  // where a manager sits.
  const pos = {};
  mgrs.forEach((m, i) => {
    const p = personas[m.manager_id];
    pos[m.manager_id] = (p && Number.isInteger(p.profile_order)) ? p.profile_order : i;
  });

  const ordered = mgrs.slice().sort((a, b) => pos[a.manager_id] - pos[b.manager_id]);
  el.innerHTML = `<ul class="pf-contents-list">${ordered.map((m) =>
    `<li><a href="#${esc(encodeURIComponent(m.manager_id))}">${esc(m.display_name)}</a></li>`
  ).join('')}</ul>`;
  show(el);
}

// ---------- nav ------------------------------------------------------------
// Same PAGE_NAV as the home page. Entries whose page is unbuilt (kind 'soon')
// are omitted rather than linked at nothing. The current page is marked, not
// linked.
function renderNav(groupId) {
  const nav = $('page-nav');
  const { raw: q, attr: qAttr } = navQuery(groupId);
  nav.innerHTML = PAGE_NAV.filter((p) => p.kind !== 'soon').map((p) => {
    if (p.href === 'managers.html') {
      return `<span class="nav-btn" aria-current="true">${esc(p.label)}</span>`;
    }
    return `<a class="nav-btn" href="${esc(p.href)}${qAttr}">${esc(p.label)}</a>`;
  }).join('');
  $('brand-link').setAttribute('href', `index.html${q}`);
}

function fail(title, body) {
  hide($('loading'));
  $('load-error').innerHTML = `<h2>${title}</h2><p>${body}</p>`;
  show($('load-error'));
}

// ---------- no masthead banner --------------------------------------------
// renderBanner() lived here and is gone. The slot came off managers.html when
// the band was removed from the profile scroll, and a function no surface
// calls is not a spare part — it is a second, drifting answer to "how does
// this site show a banner" sitting next to app.js's bannerFor(), which is the
// one the home page actually uses.
//
// The rotator's inputs are still on disk and untouched:
// data/<group>/banners.json (written by scripts/build_banners.py, panel only)
// and assets/banners/panel/*.png. Nothing reads them today. If a surface ever
// wants the band back, the manifest is the spec and build_banners.py is the
// generator; scripts/test_banners.py still holds both to the disk.

// The browser tries its hash scroll before this page has any content, so the
// jump has to be redone once the profiles exist. Without this, every
// managers.html?group=X#someone link lands at the top of the page.
//
// It then has to be redone a SECOND time: portraits take their real height on
// load, so every profile above the target grows or shrinks underneath the
// scroll we just performed. The re-jump is skipped if the reader has scrolled
// in the meantime — landing imperfectly is a smaller sin than yanking the page
// out from under someone.
let jumpedAt = null;

function jumpToHash() {
  if (!location.hash || location.hash.length < 2) return;
  let el = null;
  try {
    el = document.getElementById(decodeURIComponent(location.hash.slice(1)));
  } catch (e) {
    el = null;                       // malformed percent-encoding: no jump
  }
  if (!el) return;
  el.scrollIntoView({ block: 'start' });
  jumpedAt = Math.round(window.scrollY);
}

window.addEventListener('load', () => {
  if (jumpedAt !== null && Math.abs(window.scrollY - jumpedAt) <= 2) jumpToHash();
}, { once: true });

// ---------- boot -----------------------------------------------------------
async function main() {
  const groupId = currentGroupId();

  // Unknown league: name it and stop, exactly as app.js does. A wrong ?group=
  // must never quietly render the first league's people.
  if (groupId === null) {
    fail(`Unknown league &quot;${esc(groupParam())}&quot;.`,
      'No profiles were loaded. <a href="index.html">Back to all leagues &rarr;</a>');
    return;
  }

  renderNav(groupId);
  $('group-label').textContent = groupLabel(groupId);
  document.title = `${groupLabel(groupId)} — Manager Profiles`;

  // One round trip. Only standings is required; every other file is allowed to
  // 404 so a league with no personas, no art, no team marks and no banner
  // manifest still renders every profile.
  //
  // projection.json is NOT among them any more. It was fetched for exactly one
  // value — P(win pool) in the stat strip — and with the strip gone there is
  // nothing on this page a model produces. A page that reads a file it does not
  // render is a page that will grow a use for it by accident.
  //
  // banners.json is NOT among them any more, for the same reason
  // projection.json is not: this page has no banner slot to paint it into.
  // The manifest still exists and the home page still reads it — the fetch
  // was removed here, not the file.
  const [personasRes, standingsRes, slotsRes, portraitsRes, marksRes, heroesRes] =
    await Promise.all([
      fetchJSON(`data/${groupId}/personas.json`).catch(() => null),
      fetchJSON(`data/${groupId}/standings.json`).catch((e) => ({ $error: e })),
      fetchJSON('assets/art_slots.json').catch(() => null),
      fetchJSON('assets/portraits/index.json').catch(() => null),
      fetchJSON('data/team_marks.json').catch(() => null),
      fetchJSON('assets/profiles/heroes.json').catch(() => null),
    ]);

  if (!standingsRes || standingsRes.$error) {
    const msg = standingsRes && standingsRes.$error ? standingsRes.$error.message : 'unknown error';
    fail(`Can&rsquo;t load ${esc(groupLabel(groupId))}`,
      `standings.json is missing or unreadable (${esc(msg)}). If this league exists, ` +
      `its data may not have been generated yet.`);
    return;
  }

  ART_SLOTS = slotsRes || {};
  const standings = standingsRes;
  const meta = standings.meta || {};
  const personas = (personasRes && personasRes.managers) || {};
  const marks = (marksRes && marksRes.teams) || {};
  const heroSizes = (heroesRes && heroesRes.sizes) || {};

  // Team colour as the accent fallback when a manager has no persona theme.
  const rawPortraits = portraitsRes ? (portraitsRes[groupId] || {}) : {};
  const colors = {};
  Object.keys(rawPortraits).forEach((k) => {
    if (rawPortraits[k] && rawPortraits[k].color) colors[k] = rawPortraits[k].color;
  });

  const mgrs = (standings.managers || []).slice().sort((a, b) => a.rank - b.rank);
  const names = {};
  mgrs.forEach((m) => { names[m.manager_id] = m.display_name; });

  // The sample-data band. Read off standings.json meta.draft_status; dummy
  // picks must never read as a real draft, least of all on the page that lays
  // out every pick a manager holds.
  renderSampleBanner(meta);

  const wk = weekLabel(meta.as_of_week, isPreseasonStandings(standings));
  $('mgr-intro').innerHTML =
    `<p class="pf-intro-kicker">Profiles</p>
     <h1 class="pf-intro-title">${esc(groupLabel(groupId))}</h1>
     <p class="pf-intro-sub">${mgrs.length} manager${mgrs.length === 1 ? '' : 's'}, ` +
    `in standings order &middot; ${esc(wk)}</p>`;
  show($('mgr-intro'));

  renderContents(mgrs, personas);

  const ctx = {
    groupId,
    week: meta.as_of_week,
    season: meta.season || '',
    names,
    colors,
    marks,
    heroSizes,
  };
  $('mgr-list').innerHTML =
    mgrs.map((m, i) => profile(m, personas[m.manager_id], ctx, i)).join('');

  // An art file declared in art_slots.json but missing on disk would otherwise
  // leave a broken-image icon in the middle of the layout. Drop the portrait
  // instead and re-tag the profile, which lands it in exactly the no-art tier
  // the layout override above describes.
  //
  // The VARIANT has to be rewritten too, not just the class: a SIDELINE
  // profile whose picture 404s is a two-column composition with an empty
  // column, which is the "straight profile that looks like a roast page with
  // holes" failure in a different costume.
  $('mgr-list').querySelectorAll('.pf-portrait img').forEach((img) => {
    const drop = () => {
      const fig = img.closest('.pf-portrait');
      const card = img.closest('.pf');
      if (fig) fig.remove();
      if (card) {
        card.classList.add('has-no-art');
        Object.keys(LAYOUT_TEMPLATES).forEach((k) => card.classList.remove(`pf--${k}`));
        // The side goes with the variant. A DOSSIER still carrying
        // pf--align-right is a class describing a portrait column that no
        // longer exists — see the note on alignCls in profile().
        card.classList.remove('pf--align-right');
        card.classList.add('pf--dossier');
      }
    };
    if (img.complete && img.naturalWidth === 0) drop();
    else img.addEventListener('error', drop, { once: true });
  });

  hide($('loading'));
  jumpToHash();
}

main();
