/* ==========================================================================
   managers.js — THE manager profile page (managers.html).

   THE ONLY ONE. profile.html was a second, single-manager view of the same
   four files; it was retired and this page absorbed what it did better. A
   reader who wants one person deep-links to them (#<manager_id>) and lands on
   their card in the stack. Everything the retired page rendered renders here.

   GROUP-GENERIC BY CONSTRUCTION. There is no roster, no manager id, and no
   group path anywhere in this file. It renders whatever standings.json hands
   back for ?group=, in rank order, and treats EVERY persona field as optional.
   That is not defensive politeness: 18 of the 22 managers across the other two
   leagues launch with no persona content whatsoever, and each of them still
   has to look like a finished card rather than a broken one.

   Reads, in one Promise.all:
     data/<group>/personas.json    prose  — GENERATED by scripts/sync_personas.py
     data/<group>/standings.json   exact  — the picks, and nothing else now
     assets/art_slots.json         which picture, via resolveArt()
     assets/portraits/index.json   team color fallback when no persona color

   NO projection.json. Every number on this page is exact arithmetic off
   standings.json; the model lives on the home page's Board 2 and on
   analytics.html, which are built to frame it.

   Only standings.json is required. Every other file is allowed to 404: that is
   the normal state for a league with no art and no prose, and the page must
   degrade to "picks and a name" without a placeholder anywhere.

   THE TONE GATE is the one rule in here that is not cosmetic. See TONE_BLOCKS.
   ========================================================================== */
'use strict';

// fmtSigned / fmtLine / pct, the TONE_BLOCKS gate, toneOf() and has() live in
// site.js. They moved there when a second page needed the identical rules, and
// they stay there now that this is the only page that reads them: the tone gate
// is the one rule on this site where a second copy would be a second,
// silently-drifting answer to "may this person be captioned with a fatal flaw",
// and analytics.html and index.html still share the formatters. Read them
// there — the reasoning is documented at the definitions. These are classic
// scripts sharing one global lexical scope, so they are in scope here by name.

// ---------- blocks ---------------------------------------------------------

// 1 — art panel. resolveArt() returns null for a group that declares no
// profile art, which is family and church today. Null means the panel is not
// emitted AT ALL and the copy takes the full width: no grey box, no
// placeholder, no alt stub, no empty gutter. A manager without a picture
// should look like a manager whose card was designed without one.
//
// TWO SLOTS, TRIED IN ORDER. profile_page_hero is the torn, alpha-keyed cut;
// profile_hero is the opaque bordered rectangle and the fallback for every
// group that never declared the page slot. Both names survive the retirement of
// profile.html -- they name CUTS OF ART, not pages, and art_slots.json is not
// this thread's to rewrite. This page is now the only consumer of either.
//
// WHY .is-bleed IS GATED ON THE TWO SLOTS DISAGREEING, and not simply on
// profile_page_hero answering: family declares profile_page_hero pointing at
// the SAME file as profile_hero (its art is real photographs, deliberately
// never given a torn edge -- see art_slots.json). Keying the frameless
// treatment on "the page slot answered" would therefore strip the frame off
// every family card for a cut that does not exist. The treatment belongs to a
// DISTINCT cut, so that is exactly what is tested. A group whose two slots
// name one file renders precisely as it did before this change.
//
// RETURNS { html, isCut }, not a string, because isCut decides more than the
// frame: see profile() for why a torn row cannot be flipped.
function artPanel(groupId, managerId, name, week) {
  const cut = resolveArt(groupId, 'profile_page_hero', week, { id: managerId });
  const card = resolveArt(groupId, 'profile_hero', week, { id: managerId });
  const src = cut || card;
  // A torn, alpha-keyed cut inside a bordered figure reads as a rendering
  // fault -- the tear shows the card ground through a hard 1px edge. When the
  // cut is genuinely distinct the frame comes off and the art sits on the
  // page, which is the treatment the cut was made for.
  const isCut = !!(cut && cut !== card);
  if (!src) return { html: '', isCut: false };
  // NOT lazy. The hero is this page's primary content, not a below-fold
  // decoration, and there is one per manager -- four today, and the only
  // league that declares any. Lazy-loading them meant every card below the
  // fold rendered its art column as reserved-but-empty in any full-page
  // capture or on a slow connection, which reads as the no-art empty state
  // when it is nothing of the kind. Revisit if a league ever ships enough
  // profile art for the page weight to matter.
  return {
    html: `<figure class="mgr-art${isCut ? ' is-bleed' : ''}">
    <img class="mgr-art-img" src="${esc(src)}" alt="${esc(name)}" decoding="async">
  </figure>`,
    isCut,
  };
}

// 2 + 3 — epithet kicker, display name, and the name line beneath it.
// With no epithet the kicker is dropped and the name takes the larger size
// (.is-solo), so the block reads as designed rather than as a gap where a
// kicker should have been.
function nameBlock(m, p) {
  const epithet = p && has(p.epithet) ? p.epithet : null;
  const tagline = p && has(p.tagline) ? p.tagline : null;
  return (epithet ? `<p class="mgr-kicker">${esc(epithet)}</p>` : '') +
    `<h2 class="mgr-display${epithet ? '' : ' is-solo'}">${esc(m.display_name)}</h2>` +
    (tagline ? `<p class="mgr-realname">${esc(tagline)}</p>` : '');
}

// 4 — NO STAT STRIP. Banked, floor–ceiling and rank are the standings board's
// three columns and analytics.html's race module renders all three again;
// P(win pool) is Board 2 on the home page and the championship_odds module on
// analytics. Printing the same four numbers a third time made this page look
// like a scoreboard it is not: the picks below are what a profile adds, and
// the numbers belong to the pages built to rank them.
//
// THE PROJECTION DISCLAIMER WENT WITH IT, and that is the load-bearing half.
// P(win pool) was the only model number on this page, and the rule is that a
// model number never ships without the sentence that says it is one. Removing
// the number removes the obligation; leaving the sentence behind would have
// been a disclaimer attached to nothing, characterising a projection this page
// no longer shows. Everything that renders here now is either persona prose or
// exact arithmetic off standings.json, so projection.json is not fetched at
// all — see main().

// 5 — picks. ALWAYS renders. This is the page's guarantee that a manager with
// zero flavor content still gets a real card: live scoring is something
// everybody has.
// FOUR COLUMNS, DOWN FROM SIX.
//
// Status is gone. CLINCHED / LIVE / DEAD is derivable from the numbers already
// in the row, it is a full column of repeated words at every width, and the
// standings board carries it as a status dot on every chip. The one thing it
// did that nothing else does — dimming a settled row — is kept: .is-dead still
// rides on the row, off the same contract token.
//
// Line and O/U are one cell. They were never two facts: "9.5" and "Under" is a
// single statement, and splitting it put a bare number in a column of its own
// where it read as a score. Together, the number takes the direction's colour
// — green for an Over, red for an Under, straight off --positive / --negative —
// and keeps the shared .dir-badge pill beside it, the same pill the standings
// board prints. The colour is a second encoding of the pill, never the only
// one: it is never the sole carrier of the Over/Under distinction.
function pickTable(m) {
  const picks = m.picks || [];
  // The header cells carry the SAME per-column classes as the body cells.
  // Without them the narrow-screen fold — which places each column by name —
  // silently misses the header and leaves the labels stacked above a correctly
  // folded table.
  const head = `<div class="mgr-pick-row is-head">
    <span class="mgr-pick-team">Team</span>
    <span class="mgr-pick-conf">Conf</span>
    <span class="mgr-pick-lineou">Line</span>
    <span class="mgr-pick-delta">&Delta;</span>
  </div>`;
  if (!picks.length) {
    // Pre-draft is a real state, not a failure — say so instead of printing
    // an empty table.
    return `<div class="mgr-picks">${head}
      <p class="mgr-picks-empty">No picks yet — this league hasn&rsquo;t drafted.</p>
    </div>`;
  }
  const rows = picks.map((p) => {
    const over = p.direction === 'O';
    const d = Number(p.banked_delta);
    const dCls = d > 0 ? ' pos' : d < 0 ? ' neg' : '';
    return `<div class="mgr-pick-row${p.status === 'DEAD' ? ' is-dead' : ''}">
      <span class="mgr-pick-team">${esc(p.team)}</span>
      <span class="mgr-pick-conf">${esc(p.conference || '—')}</span>
      <span class="mgr-pick-lineou">
        <span class="mgr-pick-num mono ${over ? 'pos' : 'neg'}">${fmtLine(p.line)}</span>
        <span class="dir-badge ${over ? 'over' : 'under'}">${over ? 'Over' : 'Under'}</span>
      </span>
      <span class="mgr-pick-delta mono${dCls}">${fmtSigned(d)}</span>
    </div>`;
  }).join('');
  return `<div class="mgr-picks">${head}${rows}</div>`;
}

// 6 — backstory. Paragraphs are split on a blank line, exactly as authored in
// groups/<group>/personas.md. Absent backstory hides the block entirely.
function prose(p) {
  if (!p || !has(p.backstory)) return '';
  const paras = String(p.backstory).split(/\n\s*\n/)
    .map((t) => t.trim()).filter(Boolean);
  if (!paras.length) return '';
  return `<div class="mgr-prose">${paras.map((t) => `<p>${esc(t)}</p>`).join('')}</div>`;
}

// 7 — the persona cards: draft tendency, fatal flaw, running gag, rival.
//
// CARRIED OVER FROM THE RETIRED profile.html, which had this right and this
// page did not. Here, tendency and flaw were a two-up card grid and then gag
// and rival were dropped underneath as bordered lines — two treatments for
// four blocks that are the same KIND of thing. That split was an artifact of
// the order they were written in, not a distinction anyone meant. One grid,
// one card each, and a typographic mark per BLOCK — never per person: this
// file cannot know that a particular manager's gag is about Texas.
//
// auto-fit is load-bearing rather than cosmetic, and it is why the old
// `.is-solo` special case is gone: THE TONE GATE decides how many cards exist.
// A straight-register manager gets exactly one, a roast-register manager with
// a full persona gets four, and every count between happens. A fixed column
// count sits the one-card manager beside that many empty cells.
//
// Rival is a SAME-PAGE anchor, and only when the rival is someone this render
// actually produced — an id that never rendered would be a dead jump.
// sync_personas.py already rejects a rival that is not a manager_id in the
// group; this catches the narrower case where the roster and this render
// disagree.
function metaCards(p, allow, names) {
  const cards = [];
  if (p && has(p.draft_tendency)) {
    cards.push({ icon: '\u21c4', title: 'Draft tendency', copy: esc(p.draft_tendency) });
  }
  if (allow.fatal_flaw && p && has(p.fatal_flaw)) {
    cards.push({ icon: '!', title: 'Fatal flaw', copy: esc(p.fatal_flaw) });
  }
  if (allow.running_gag && p && has(p.running_gag)) {
    cards.push({ icon: '\u21bb', title: 'Running gag', copy: esc(p.running_gag) });
  }
  if (allow.rival && p && has(p.rival) &&
      Object.prototype.hasOwnProperty.call(names, String(p.rival))) {
    const rid = String(p.rival);
    cards.push({
      icon: '\u2694',
      title: 'Rival',
      copy: `<a href="#${encodeURIComponent(rid)}">${esc(names[rid])}</a>`,
    });
  }
  if (!cards.length) return '';
  return `<div class="mgr-meta">${cards.map((c) => `<div class="mgr-metacard">
    <div class="mgr-metacard-head">
      <span class="mgr-metaicon" aria-hidden="true">${c.icon}</span>
      <span class="mgr-metacard-lbl">${esc(c.title)}</span>
    </div>
    <p class="mgr-metacard-txt">${c.copy}</p>
  </div>`).join('')}</div>`;
}

// ---------- one profile ----------------------------------------------------
function profile(m, persona, ctx, index) {
  const p = persona || null;
  const allow = toneOf(p);
  const art = artPanel(ctx.groupId, m.manager_id, m.display_name, ctx.week);
  // THE TEAR DECIDES THE SIDE, AND THE TEAR IS ON THE RIGHT.
  //
  // Art alternates sides down the page, and the torn cut has to face the copy:
  // the ragged edge is meant to read as the page tearing away, which only works
  // where it dissolves into the words rather than into the margin. On a flipped
  // row the art sits right, so a right-hand tear points at the page edge and
  // the straight machine-cut left edge butts against the copy -- exactly
  // backwards, and visible today on every odd-indexed manager.
  //
  // MIRRORING THE ART IS THE OBVIOUS FIX AND IT IS NOT AVAILABLE. All fifteen
  // -ripped assets across panel, church and browns are cut with the tear on the
  // RIGHT (measured: left edge inset 0.0px at sd 0.0, right edge 18-52px at sd
  // 12-29 -- a straight cut against a ragged one), so a scaleX(-1) on the
  // flipped rows would put every tear where it belongs. But this art carries
  // baked-in lettering: "I'M A MAN, I'M 40!" across Blaine, "AIN'T JUST FAST.
  // IT'S FAT PRIME" and a Colorado scoreboard across Chris, BULLDOGS across
  // David. A mirror renders all of it backwards. The tear is fixed in the
  // pixels and cannot move, so the LAYOUT yields instead: a torn row is never
  // flipped, and its art stays left where the tear faces the copy.
  //
  // Only torn rows give up the alternation. A group whose page slot names the
  // same file as the card slot -- family, whose art is photographs deliberately
  // never given a ragged edge -- has no tear to point anywhere and keeps
  // alternating exactly as before. If a future set of assets is cut with the
  // tear on the left, this is the line that has to learn about it; the frame
  // treatment in artPanel() does not.
  const side = !art.html ? ' has-no-art'
    : (art.isCut || index % 2 === 0) ? '' : ' is-flipped';
  // --mc is used for RULES AND FILLS ONLY, never for text. Team colors are
  // picked for helmets: Colorado #cfb87c sits at 1.94:1 on white. Keeping it
  // out of type is why this page needs no contrast-fitting pass.
  const mc = p && has(p.color) ? p.color
    : (ctx.colors[m.manager_id] || null);
  const style = mc ? ` style="--mc:${esc(mc)}"` : '';

  return `<article class="mgr-profile${side}" id="${esc(m.manager_id)}"${style}>
    ${art.html}
    <div class="mgr-copy">
      ${nameBlock(m, p)}
      ${pickTable(m)}
      ${prose(p)}
      ${metaCards(p, allow, ctx.names)}
      <p class="mgr-top">
        <a href="#${esc(encodeURIComponent(m.manager_id))}">Link to ${esc(m.display_name)} &rarr;</a>
        <a href="#top">&uarr; Back to top</a>
      </p>
    </div>
  </article>`;
}

// ---------- nav ------------------------------------------------------------
// Same PAGE_NAV as the home page. Entries whose page is unbuilt (kind 'soon')
// are omitted rather than linked at nothing — this page has no COMING SOON
// panel to swap in, and a tab that does nothing is worse than one that is
// absent. The current page is marked, not linked.
function renderNav(groupId) {
  const nav = $('page-nav');
  const { raw: q, attr: qAttr } = navQuery(groupId);
  nav.innerHTML = PAGE_NAV.filter((p) => p.kind !== 'soon').map((p) => {
    if (p.href === 'managers.html') {
      return `<span class="nav-btn" aria-current="true">${esc(p.label)}</span>`;
    }
    return `<a class="nav-btn" href="${esc(p.href)}${qAttr}">${esc(p.label)}</a>`;
  }).join('');
  $('brand-link').setAttribute('href', `index.html${q}`);
}

function fail(title, body) {
  hide($('loading'));
  $('load-error').innerHTML = `<h2>${title}</h2><p>${body}</p>`;
  show($('load-error'));
}

// The browser tries its hash scroll before this page has any content, so the
// jump has to be redone once the profiles exist. Without this, every
// managers.html?group=X#someone link lands at the top of the page.
//
// It then has to be redone a SECOND time: each art panel starts at a reserved
// placeholder ratio and takes its real height on load, so every card above the
// target grows or shrinks underneath the scroll we just performed and the
// reader lands somewhere in the middle of the person they followed a link to.
// The re-jump is skipped if the reader has scrolled in the meantime — landing
// imperfectly is a smaller sin than yanking the page out from under someone.
let jumpedAt = null;

function jumpToHash() {
  if (!location.hash || location.hash.length < 2) return;
  let el = null;
  try {
    el = document.getElementById(decodeURIComponent(location.hash.slice(1)));
  } catch (e) {
    el = null;                       // malformed percent-encoding: no jump
  }
  if (!el) return;
  el.scrollIntoView({ block: 'start' });
  jumpedAt = Math.round(window.scrollY);
}

window.addEventListener('load', () => {
  if (jumpedAt !== null && Math.abs(window.scrollY - jumpedAt) <= 2) jumpToHash();
}, { once: true });

// ---------- boot -----------------------------------------------------------
async function main() {
  const groupId = currentGroupId();

  // Unknown league: name it and stop, exactly as app.js does. A wrong ?group=
  // must never quietly render the first league's people.
  if (groupId === null) {
    fail(`Unknown league &quot;${esc(groupParam())}&quot;.`,
      'No profiles were loaded. <a href="index.html">Back to all leagues &rarr;</a>');
    return;
  }

  renderNav(groupId);
  $('group-label').textContent = groupLabel(groupId);
  document.title = `${groupLabel(groupId)} — Manager Profiles`;

  // One round trip. Only standings is required; every other file is allowed to
  // 404 so a league with no personas and no art still renders every card.
  //
  // projection.json is NOT among them any more. It was fetched for exactly one
  // value — P(win pool) in the stat strip — and with the strip gone there is
  // nothing on this page a model produces. A page that reads a file it does not
  // render is a page that will grow a use for it by accident.
  const [personasRes, standingsRes, slotsRes, portraitsRes] =
    await Promise.all([
      fetchJSON(`data/${groupId}/personas.json`).catch(() => null),
      fetchJSON(`data/${groupId}/standings.json`).catch((e) => ({ $error: e })),
      fetchJSON('assets/art_slots.json').catch(() => null),
      fetchJSON('assets/portraits/index.json').catch(() => null),
    ]);

  if (!standingsRes || standingsRes.$error) {
    const msg = standingsRes && standingsRes.$error ? standingsRes.$error.message : 'unknown error';
    fail(`Can&rsquo;t load ${esc(groupLabel(groupId))}`,
      `standings.json is missing or unreadable (${esc(msg)}). If this league exists, ` +
      `its data may not have been generated yet.`);
    return;
  }

  ART_SLOTS = slotsRes || {};
  const standings = standingsRes;
  const meta = standings.meta || {};
  const personas = (personasRes && personasRes.managers) || {};

  // Team color as the fallback accent when a manager has no persona color.
  // Same manifest app.js reads; absent means no accent at all, which the CSS
  // handles by falling back to the site's own rule color.
  const rawPortraits = portraitsRes ? (portraitsRes[groupId] || {}) : {};
  const colors = {};
  Object.keys(rawPortraits).forEach((k) => {
    if (rawPortraits[k] && rawPortraits[k].color) colors[k] = rawPortraits[k].color;
  });

  const mgrs = (standings.managers || []).slice().sort((a, b) => a.rank - b.rank);
  const names = {};
  mgrs.forEach((m) => { names[m.manager_id] = m.display_name; });

  // Was a local `null ? 'Live' : 'Week N'`, which called a preseason board
  // "Live" while index.html and analytics.html called the same standings.json
  // "Preseason". Same helper, same predicate, same answer as the other two now.
  const wk = weekLabel(meta.as_of_week, isPreseasonStandings(standings));
  $('mgr-intro').innerHTML =
    `<p class="mgr-intro-kicker">Profiles</p>
     <h1 class="mgr-intro-title">${esc(groupLabel(groupId))}</h1>
     <p class="mgr-intro-sub">${mgrs.length} manager${mgrs.length === 1 ? '' : 's'}, ` +
    `in standings order &middot; ${esc(wk)}</p>`;
  show($('mgr-intro'));

  const ctx = { groupId, week: meta.as_of_week, names, colors };
  $('mgr-list').innerHTML =
    mgrs.map((m, i) => profile(m, personas[m.manager_id], ctx, i)).join('');

  // An art file declared in art_slots.json but missing on disk would otherwise
  // leave a broken-image icon in the middle of the layout. Drop the whole
  // panel instead, which lands the card in exactly the no-art layout above.
  $('mgr-list').querySelectorAll('img.mgr-art-img').forEach((img) => {
    const drop = () => {
      const fig = img.closest('.mgr-art');
      const card = img.closest('.mgr-profile');
      if (fig) fig.remove();
      if (card) card.classList.add('has-no-art');
    };
    // The art is lazy-loaded, so until it arrives the browser knows no
    // intrinsic size and the figure collapses to its own border — a 4px bar
    // sitting in an otherwise empty 340px column. .mgr-art holds a placeholder
    // aspect ratio to reserve that space, and this releases it to the image's
    // real proportions on load. Reserving the box is NOT the same as the
    // no-art placeholder the empty-state rule forbids: this manager has a
    // picture, it just has not arrived yet.
    const settle = () => { const f = img.closest('.mgr-art'); if (f) f.classList.add('is-loaded'); };
    if (img.complete) (img.naturalWidth === 0 ? drop : settle)();
    else {
      img.addEventListener('load', settle, { once: true });
      img.addEventListener('error', drop, { once: true });
    }
  });

  hide($('loading'));
  jumpToHash();
}

main();
