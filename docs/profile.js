/* ==========================================================================
   profile.js — the single-manager page (profile.html).

   ONE MANAGER, FULL PAGE. managers.html is the roster view: every manager in
   a league, stacked, in standings order. This is the leaf — ?group= names the
   league, ?id= names the person, and the page is built for a URL that gets
   shared on its own with no other context around it.

   GROUP-GENERIC AND MANAGER-GENERIC. There is no roster, no manager id and no
   group path in this file. Every persona field is optional: 18 of the 22
   managers across the other leagues have no persona content whatsoever, and
   each of them still has to come out looking like a finished page rather than
   a broken one. What always renders is the stat strip and the picks table —
   live scoring is the one thing everybody has.

   Reads exactly the files managers.js reads, and no others:
     data/<group>/personas.json    prose  — GENERATED by scripts/sync_personas.py
     data/<group>/standings.json   exact  — banked total, floor/ceiling, rank, picks
     data/<group>/projection.json  model  — P(win pool)
     assets/art_slots.json         which picture, via resolveArt()

   Only standings.json is required; the rest are allowed to 404, which is the
   normal state for a league with no art and no prose.

   The tone gate (TONE_BLOCKS/toneOf) and the number formatters come from
   site.js — the same ones managers.js uses, deliberately not re-declared
   here. See the note at their definitions.
   ========================================================================== */
'use strict';

// ---------- URL state ------------------------------------------------------
// ?id= has no default, and that is the point. currentGroupId() may fall back
// to the first league because a bare index.html is a meaningful request; a
// bare profile.html is not — "some manager" is not a thing anyone asked for,
// and guessing one would put a stranger's face under a shared URL.
function managerParam() {
  return new URLSearchParams(location.search).get('id');
}

// Every internal link on this page carries the group query, or the first click
// drops a scoped reader back onto the master view. profileHref adds ?id= for
// links that point at another manager's page.
function profileHref(groupId, managerId) {
  return `profile.html?group=${encodeURIComponent(groupId)}` +
    `&amp;id=${encodeURIComponent(managerId)}${isScoped() ? '&amp;scoped=1' : ''}`;
}

// ---------- blocks ---------------------------------------------------------

// 1 — hero art. resolveArt() returns null for a league that declares no
// profile art, which is family and church today. Null means the media column
// is not emitted AT ALL and the copy takes the full width: no grey box, no
// placeholder, no empty gutter.
//
// The art is NOT lazy-loaded and NOT cropped. It is this page's primary
// content, above the fold, one image per page — and it is poster-format with
// the lettering baked in, which is why profile.css contains it rather than
// covering it. See the no-crop rule there.
//
// TWO SLOTS, TRIED IN ORDER. profile_page_hero is this page's own surface: a
// cut of the art made for standing alone on paper, which today means the
// alpha-keyed torn edge. It is declared for almost nobody. profile_hero is
// the roster card's art and the fallback for everyone else, so a league that
// never heard of the new slot renders exactly as it did before the slot
// existed. Never merge the two — the roster card wants the opaque cut.
function heroArt(groupId, managerId, name, week, sizes) {
  // Which slot answered is not just bookkeeping — it decides the treatment.
  // profile_page_hero is this page's own surface and its art bleeds to the
  // panel edges (.is-bleed). profile_hero is the roster card's art and the
  // fallback for any group that never declared the page slot; that art is an
  // ordinary bordered rectangle, so it is contained, never cropped, and never
  // gets the class.
  const bleed = resolveArt(groupId, 'profile_page_hero', week, { id: managerId });
  const src = bleed || resolveArt(groupId, 'profile_hero', week, { id: managerId });
  if (!src) return '';
  // The aspect up front, from the manifest, so the panel is the right width
  // on the first paint instead of snapping to it when the image decodes. An
  // unknown path (or no manifest at all) just falls back to the CSS default
  // and is corrected on load.
  const wh = sizes && sizes[src];
  const ar = wh && wh[0] > 0 && wh[1] > 0
    ? ` style="--pf-ar:${(wh[0] / wh[1]).toFixed(4)}"` : '';
  return `<div class="pf-hero-media${bleed ? ' is-bleed' : ''}"${ar}>
    <img id="pf-art" src="${esc(src)}" alt="${esc(name)}" decoding="async">
  </div>`;
}

// 2 — epithet kicker, name, tagline. With no epithet the kicker is dropped
// rather than left as an empty orange line. Rank is NOT here — it is the
// third cell of the stat strip below.
function nameBlock(m, p) {
  const epithet = p && has(p.epithet) ? p.epithet : null;
  const tagline = p && has(p.tagline) ? p.tagline : null;
  return (epithet ? `<p class="pf-kicker">${esc(epithet)}</p>` : '') +
    `<h1 class="pf-name">${esc(m.display_name)}</h1>
    <div class="pf-rule"></div>` +
    (tagline ? `<p class="pf-tagline">${esc(tagline)}</p>` : '');
}

// 3 — stat strip. ALWAYS renders. Three exact numbers off standings.json
// (banked, the floor–ceiling range, rank) and one model number off
// projection.json.
//
// P(win pool) is Board 2, and Board 2's rule travels with the number: it
// carries the same "Projection" tag and the same disclaimer sentence the home
// page prints under its win-probability card, built from the same
// projection.meta.ratings_source. This page is a single manager reached by a
// shared link, so a reader can arrive here having seen nothing else on the
// site — which is exactly why the disclaimer ships attached to the number and
// not once at the top of some other page.
function statStrip(m, proj, projNote) {
  const total = Number(m.banked_total);
  // Only the headline cell is coloured. A green banked total next to a green
  // range next to a green percentage is three greens saying nothing.
  const totalCls = total < 0 ? ' neg' : '';
  const win = proj && proj.p_win_pool !== undefined && proj.p_win_pool !== null
    ? pct(proj.p_win_pool) : '&mdash;';
  // rank is required by the output contract, but a league mid-regeneration
  // could hand us a row without one; an em dash beats "#undefined".
  const rank = has(m.rank) ? `#${esc(m.rank)}` : '&mdash;';
  return `<div class="pf-stats">
    <div class="pf-stat is-primary">
      <span class="pf-stat-val${totalCls}">${fmtSigned(total)}</span>
      <span class="pf-stat-lbl">Banked</span>
    </div>
    <div class="pf-stat is-range">
      <span class="pf-stat-val">${fmtSigned(m.floor)} &ndash; ${fmtSigned(m.ceiling)}</span>
      <span class="pf-stat-lbl">Floor &ndash; ceiling</span>
    </div>
    <div class="pf-stat is-rank">
      <span class="pf-stat-val">${rank}</span>
      <span class="pf-stat-lbl">Rank</span>
    </div>
    <div class="pf-stat">
      <span class="pf-stat-val">${win}</span>
      <span class="pf-stat-lbl">P(win pool)</span>
      <span class="pf-tag">Projection</span>
    </div>
  </div>
  <p class="pf-note">${projNote}</p>`;
}

// 4 — picks. ALWAYS renders, alongside the stat strip. This pair is the
// page's guarantee that a manager with zero flavor content still gets a real
// page.
//
// Rows are a CSS grid, not a <table>. The narrow layout re-flows each pick
// into a 2x3 block by placing every cell individually — grid-column and
// grid-row per class — which a table's display model cannot do without being
// unwound into blocks first. The head shares the row's exact template so the
// columns cannot drift apart.
function pickTable(m) {
  const picks = m.picks || [];
  if (!picks.length) {
    // Pre-draft is a real state, not a failure — say so instead of printing
    // an empty table with a header and nothing under it.
    return `<p class="pf-picks-empty">No picks yet &mdash; this league hasn&rsquo;t drafted.</p>`;
  }
  const rows = picks.map((p) => {
    const over = p.direction === 'O';
    const d = Number(p.banked_delta);
    const dCls = d < 0 ? ' neg' : d === 0 ? ' flat' : '';
    const stCls = p.status === 'LIVE' ? 'st-live'
      : p.status === 'CLINCHED' ? 'st-clinched' : 'st-dead';
    // Title-case for display only. status stays the contract's upper-case
    // token in the class name, so a new state can never silently style itself
    // as CLINCHED green.
    const stTxt = String(p.status || '');
    const stLabel = stTxt ? stTxt.charAt(0) + stTxt.slice(1).toLowerCase() : '&mdash;';
    return `<div class="pf-pick-row${p.status === 'DEAD' ? ' is-dead' : ''}">
      <span class="pf-team">${esc(p.team)}</span>
      <span class="pf-conf">${esc(p.conference || '—')}</span>
      <span class="pf-line">${fmtLine(p.line)}</span>
      <span class="pf-ou"><span class="pf-pill ${over ? 'over' : 'under'}">${over ? 'Over' : 'Under'}</span></span>
      <span class="pf-delta${dCls}">${fmtSigned(d)}</span>
      <span class="pf-status"><span class="pf-pill ${stCls}">${stLabel}</span></span>
    </div>`;
  }).join('');
  return `<div class="pf-picks">
    <div class="pf-picks-head">
      <span>Team</span><span>Conf</span><span>Line</span>
      <span>O/U</span><span>&Delta;</span><span>Status</span>
    </div>
    ${rows}
  </div>`;
}

// 5 — backstory. Paragraphs split on a blank line, exactly as authored in
// groups/<group>/personas.md. Absent backstory hides the block entirely
// rather than leaving a bordered empty band across the card.
function bio(p) {
  if (!p || !has(p.backstory)) return '';
  const paras = String(p.backstory).split(/\n\s*\n/)
    .map((t) => t.trim()).filter(Boolean);
  if (!paras.length) return '';
  return `<section class="pf-bio">${paras.map((t) => `<p>${esc(t)}</p>`).join('')}</section>`;
}

// 6 — the meta cards: draft tendency, fatal flaw, running gag, rival.
//
// THE TONE GATE DECIDES WHICH OF THESE EXIST. Draft tendency renders in every
// register; the other three are withheld per register by toneOf(). A withheld
// card is never built, so there is nothing in the DOM to un-hide. The grid is
// auto-fit precisely because this returns between one and four cards.
//
// Icons are typographic marks chosen per block, not per person — this file
// cannot know that any particular manager's gag is about Texas.
function metaCards(p, allow, ctx) {
  const cards = [];
  if (p && has(p.draft_tendency)) {
    cards.push({ icon: '⇄', title: 'Draft tendency', copy: esc(p.draft_tendency) });
  }
  if (allow.fatal_flaw && p && has(p.fatal_flaw)) {
    cards.push({ icon: '!', title: 'Fatal flaw', copy: esc(p.fatal_flaw) });
  }
  if (allow.running_gag && p && has(p.running_gag)) {
    cards.push({ icon: '↻', title: 'Running gag', copy: esc(p.running_gag) });
  }
  // Rival is a link to another real page, so it renders only when the rival
  // is someone this league actually has. sync_personas.py already rejects a
  // rival that is not a manager_id in the group; this catches the narrower
  // case where the roster and this render disagree, which would otherwise
  // ship a link to a profile that fails to load.
  if (allow.rival && p && has(p.rival) &&
      Object.prototype.hasOwnProperty.call(ctx.names, String(p.rival))) {
    const rid = String(p.rival);
    cards.push({
      icon: '⚔',
      title: 'Rival',
      copy: `<a href="${profileHref(ctx.groupId, rid)}">${esc(ctx.names[rid])}</a>`,
    });
  }
  if (!cards.length) return '';
  return `<section class="pf-traits">${cards.map((c) => `<div class="pf-trait">
    <div class="pf-trait-head">
      <div class="pf-icon" aria-hidden="true">${c.icon}</div>
      <h2>${esc(c.title)}</h2>
    </div>
    <p>${c.copy}</p>
  </div>`).join('')}</section>`;
}

// 7 — the also-in rail. This page is reached by a shared link as often as by
// a click, so it must not be a dead end: the rest of the league, in standings
// order, plus the way back to the roster view.
function alsoIn(ctx, currentId) {
  const others = ctx.order.filter((id) => id !== currentId);
  if (!others.length) return '';
  const links = others.map((id) =>
    `<a href="${profileHref(ctx.groupId, id)}">${esc(ctx.names[id])}</a>`).join('');
  const { attr: qAttr } = navQuery(ctx.groupId);
  return `<span class="pf-alsoin-lbl">Also in ${esc(groupLabel(ctx.groupId))}</span>` +
    links +
    `<a href="managers.html${qAttr}">All profiles &rarr;</a>`;
}

// ---------- nav ------------------------------------------------------------
// Same PAGE_NAV as every other page. Entries whose page is unbuilt (kind
// 'soon') are omitted rather than linked at nothing.
//
// PROFILES is marked current AND stays a link: this page is a leaf of the
// roster view, so the tab both shows where the reader is and is the way back
// up to it. That is why it is not swapped for a dead <span> the way
// managers.js swaps it on the roster page itself.
function renderNav(groupId) {
  const { raw: q, attr: qAttr } = navQuery(groupId);
  $('page-nav').innerHTML = PAGE_NAV.filter((p) => p.kind !== 'soon').map((p) => {
    const cur = p.href === 'managers.html' ? ' aria-current="true"' : '';
    return `<a class="nav-btn" href="${esc(p.href)}${qAttr}"${cur}>${esc(p.label)}</a>`;
  }).join('');
  $('brand-link').setAttribute('href', `index.html${q}`);
}

// ---------- fitting the hero frame to the art -----------------------------
// Give the media column exactly the width that makes the frame the same shape
// as the picture, so it bleeds to three panel edges and `cover` has nothing to
// crop. The 22 managers' art runs from 0.47 to 0.98, so no single fraction
// works: one wide enough for the near-square pictures pillarboxes the narrow
// ones inside a third of a panel.
//
// WHY THIS IS NOT CSS. Frame width has to come from row height, and row height
// comes from the copy column, whose height depends on how wide it is — which
// depends on the frame width. CSS has no way to express that. `aspect-ratio`
// on the frame looks like the answer and is not: it stops the frame stretching
// to its row (stretch needs an auto cross size), so the column and the frame
// disagree and the gap between them shows as dead paper.
//
// So: iterate. Set a width, measure the height it produces, derive the width
// that height wants, repeat. It settles in two or three passes because each
// step moves less than the last; the loop is capped and the tolerance is
// half a pixel.
const HERO_MIN_W = 232;
const HERO_MAX_FRAC = 0.54;

function fitHero() {
  const hero = document.querySelector('.pf-hero');
  const media = document.querySelector('.pf-hero-media.is-bleed');
  if (!hero || !media) return;
  const img = $('pf-art');
  // The image's own report beats the manifest — see the note at fixAspect.
  const ar = (img && img.naturalWidth && img.naturalHeight)
    ? img.naturalWidth / img.naturalHeight
    : parseFloat(getComputedStyle(media).getPropertyValue('--pf-ar')) || 0.8;
  if (!(ar > 0)) return;

  const total = hero.getBoundingClientRect().width;
  if (!total) return;
  // Guard rails: never a slot, never so wide the copy has no room. On a phone
  // the hero is stacked and this does not run at all.
  const lo = Math.min(HERO_MIN_W, total * 0.3);
  const hi = total * HERO_MAX_FRAC;
  let w = Math.min(hi, Math.max(lo, total * 0.42));
  for (let i = 0; i < 6; i += 1) {
    hero.style.gridTemplateColumns = `${w}px minmax(0, 1fr)`;
    const next = Math.min(hi, Math.max(lo, hero.getBoundingClientRect().height * ar));
    const done = Math.abs(next - w) < 0.5;
    w = next;
    if (done) break;
  }
  hero.style.gridTemplateColumns = `${w}px minmax(0, 1fr)`;

  // Only claim the fit if it actually fits. When a clamp bit — a very wide
  // picture against a narrow window — the frame is NOT the picture's shape,
  // and switching to cover would crop it. Leaving the class off keeps the
  // safe `contain` and costs a little paper at the sides instead.
  const r = media.getBoundingClientRect();
  media.classList.toggle('is-fitted',
    r.height > 0 && Math.abs((r.width / r.height) - ar) < 0.02);
}

// The stacked layout has no media column to solve, so the inline width from a
// wider viewport has to be cleared or it survives the breakpoint as a fixed
// px column inside a one-column grid.
const HERO_STACK_MQ = window.matchMedia('(max-width: 900px)');

function layoutHero() {
  const hero = document.querySelector('.pf-hero');
  if (!hero) return;
  if (HERO_STACK_MQ.matches) {
    hero.style.gridTemplateColumns = '';
    const media = document.querySelector('.pf-hero-media.is-bleed');
    if (media) media.classList.remove('is-fitted');
    return;
  }
  fitHero();
}

function fail(title, body) {
  hide($('loading'));
  $('load-error').innerHTML = `<h2>${title}</h2><p>${body}</p>`;
  show($('load-error'));
}

// ---------- boot -----------------------------------------------------------
async function main() {
  const groupId = currentGroupId();

  // Unknown league: name it and stop, exactly as app.js and managers.js do. A
  // wrong ?group= must never quietly render the first league's people.
  if (groupId === null) {
    fail(`Unknown league &quot;${esc(groupParam())}&quot;.`,
      'No profile was loaded. <a href="index.html">Back to all leagues &rarr;</a>');
    return;
  }

  renderNav(groupId);
  $('group-label').textContent = groupLabel(groupId);

  const [personasRes, standingsRes, projRes, slotsRes, heroesRes] = await Promise.all([
    fetchJSON(`data/${groupId}/personas.json`).catch(() => null),
    fetchJSON(`data/${groupId}/standings.json`).catch((e) => ({ $error: e })),
    fetchJSON(`data/${groupId}/projection.json`).catch(() => null),
    fetchJSON('assets/art_slots.json').catch(() => null),
    fetchJSON('assets/profiles/heroes.json').catch(() => null),
  ]);

  if (!standingsRes || standingsRes.$error) {
    const msg = standingsRes && standingsRes.$error ? standingsRes.$error.message : 'unknown error';
    fail(`Can&rsquo;t load ${esc(groupLabel(groupId))}`,
      `standings.json is missing or unreadable (${esc(msg)}). If this league exists, ` +
      `its data may not have been generated yet.`);
    return;
  }

  ART_SLOTS = slotsRes || {};
  const meta = standingsRes.meta || {};
  const personas = (personasRes && personasRes.managers) || {};
  const mgrs = (standingsRes.managers || []).slice().sort((a, b) => a.rank - b.rank);

  const names = {};
  const order = [];
  mgrs.forEach((m) => { names[m.manager_id] = m.display_name; order.push(m.manager_id); });

  // No ?id= and unknown ?id= are the same failure with different words, and
  // both end in the same place: the roster, listed by name. Neither one gets
  // to pick a manager on the reader's behalf.
  const wanted = managerParam();
  const roster = order.length
    ? `<br>Managers in this league: ` + order.map((id) =>
      `<a href="${profileHref(groupId, id)}">${esc(names[id])}</a>`).join(', ') + '.'
    : '';
  if (!wanted) {
    fail('No manager named.',
      `This page needs an <code>?id=</code>.${roster}`);
    return;
  }
  const m = mgrs.find((x) => x.manager_id === wanted);
  if (!m) {
    fail(`No manager &quot;${esc(wanted)}&quot; in ${esc(groupLabel(groupId))}.`,
      `Nothing was rendered rather than showing someone else.${roster}`);
    return;
  }

  const p = personas[m.manager_id] || null;
  const allow = toneOf(p);
  const proj = ((projRes && projRes.managers) || [])
    .find((x) => x.manager_id === m.manager_id) || null;

  // The projection's own words, from its own metadata — the same sentence the
  // home page's Board 2 and the roster page print, so the three cannot
  // characterize the model differently. With no projection at all the note
  // says that instead; the strip still renders, with an em dash for the
  // number.
  const projNote = projRes
    ? `Model estimate from ${esc((projRes.meta && projRes.meta.ratings_source) || 'SP+')} ` +
      `ratings &mdash; it updates weekly and can be wrong. Banked and floor&ndash;ceiling ` +
      `above are exact arithmetic.`
    : 'The weekly projection could not be loaded, so P(win pool) is unavailable. ' +
      'The exact numbers above are unaffected.';

  const ctx = { groupId, names, order, week: meta.as_of_week };
  const sizes = (heroesRes && heroesRes.sizes) || null;
  const art = heroArt(groupId, m.manager_id, m.display_name, meta.as_of_week, sizes);

  document.title = `${m.display_name} — ${groupLabel(groupId)} — CF Challenge`;

  $('pf-card').innerHTML =
    `<section class="pf-hero${art ? '' : ' has-no-art'}">
      ${art}
      <div class="pf-hero-copy">
        ${nameBlock(m, p)}
        ${statStrip(m, proj, projNote)}
      </div>
    </section>
    <section class="pf-picks-section">
      ${pickTable(m)}
    </section>
    ${bio(p)}
    ${metaCards(p, allow, ctx)}
    <div class="pf-brush"></div>`;

  const rail = alsoIn(ctx, m.manager_id);
  if (rail) { $('pf-alsoin').innerHTML = rail; show($('pf-alsoin')); }

  // An art file declared in art_slots.json but missing on disk would leave a
  // broken-image icon filling half the hero. Drop the whole media column
  // instead, which lands the page in exactly the no-art layout above.
  const img = $('pf-art');
  if (img) {
    const drop = () => {
      const media = img.closest('.pf-hero-media');
      const hero = img.closest('.pf-hero');
      if (media) media.remove();
      if (hero) hero.classList.add('has-no-art');
    };
    // The manifest is a build artifact and the images are not; if one is
    // re-cropped without a rebuild the two disagree, and the frame would hold
    // an aspect the picture no longer has — which is the one thing that makes
    // `cover` crop here. The image's own report always wins.
    const fixAspect = () => {
      const media = img.closest('.pf-hero-media');
      if (!media || !img.naturalWidth || !img.naturalHeight) return;
      media.style.setProperty('--pf-ar',
        (img.naturalWidth / img.naturalHeight).toFixed(4));
      layoutHero();
    };
    if (img.complete) (img.naturalWidth === 0 ? drop : fixAspect)();
    else {
      img.addEventListener('load', fixAspect, { once: true });
      img.addEventListener('error', () => { drop(); layoutHero(); }, { once: true });
    }
  }

  // First pass off the manifest, before the image has decoded, so the panel
  // starts at the right width instead of snapping to it.
  layoutHero();

  // The solved width is in pixels, so it does not survive a resize on its own.
  let pending = null;
  window.addEventListener('resize', () => {
    if (pending) cancelAnimationFrame(pending);
    pending = requestAnimationFrame(() => { pending = null; layoutHero(); });
  });
  // Web fonts land after first paint and change the copy column's height,
  // which changes the width the frame wants. Without this the hero keeps the
  // width it computed against the fallback face.
  if (document.fonts && document.fonts.ready) {
    document.fonts.ready.then(layoutHero).catch(() => {});
  }

  hide($('loading'));
  show($('pf-card'));
}

main();
